#!/usr/bin/env python3
"""package_for_submission.py -- copies the two supplementary files into ../for_submission/ for download and upload:
ESM_1.xlsx (Supplementary Tables S1-S22) and ESM_2.pdf (Supplementary Figures S1-S5), a zip of both, and CAPTIONS.md
(each file with its caption, for the submission system).

TAG (journal_TAG/TAG_submission_guidelines_2026-09-15.pdf, Supplementary Information): files named ESM_1, ESM_2, ...;
spreadsheets as .xlsx, collections of figures as PDF; a concise caption for each file in the manuscript; several files
may be zipped. Since 2026-10-17 (S. Hübner's comment, user decision) the supplement is two files with internal numbering
(Table S1 ..., Fig. S1 ...), as in published TAG papers; until then it was 13 separate "Online Resources".
Captions = the "Supplementary Information" section of the manuscript (one line per file).
The unnumbered supplement (../unreferenced/) is not included: it is not cited in the text.
Run by build_all.sh after the builders (the copies are refreshed on every build). Created 2026-10-01; two files since
2026-10-17.
"""
import re, shutil, zipfile
from esm_common import SUPP, WORKING_FILE, AUTHORS, TABLES_FILE, FIGURES_FILE

OUT = SUPP / "for_submission"
if OUT.exists():
    shutil.rmtree(OUT)                         # only ever holds copies made by this script
OUT.mkdir()
files = [TABLES_FILE, FIGURES_FILE]
for f in files:
    assert f.exists(), f
    shutil.copy2(f, OUT / f.name)
ZIP = OUT / "ESM_all_supplementary.zip"
with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
    for f in files:
        z.write(f, f.name)
t = WORKING_FILE.read_text(encoding="utf-8")
sec = t[t.index("# Supplementary Information"):]
caps = {f: (label, c.strip()) for label, f, c in
        re.findall(r"\*\*(Supplementary (?:Tables|Figures) S1–S\d+)\*\* \(file (ESM_\d\.(?:xlsx|pdf))\) ([^\n]+)", sec)}
assert sorted(caps) == [f.name for f in files], sorted(caps)
plain = lambda s: re.sub(r"\*+", "", s)
lines = ["# Supplementary material (ESM) — files and captions for the TAG submission system", "",
         "Generated by `scripts/package_for_submission.py`. Upload the two files separately (or the zip), each with its caption.",
         "Captions = the \"Supplementary Information\" section of the manuscript.", ""]
if "[" in AUTHORS:
    lines += ["**Before uploading:** the title block in both files still has placeholders (author names, corresponding author's "
              "affiliation and e-mail): set them in `scripts/esm_common.py` and run `scripts/build_all.sh` (checklist item 1).", ""]
lines += ["| file | caption |", "|---|---|"] + [f"| `{f.name}` | {caps[f.name][0]}. {plain(caps[f.name][1])} |" for f in files]
(OUT / "CAPTIONS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"packaged {len(files)} files -> {OUT} ({', '.join(f.name for f in files)}, zip "
      f"{round(ZIP.stat().st_size / 1e6, 1)} MB, CAPTIONS.md)")

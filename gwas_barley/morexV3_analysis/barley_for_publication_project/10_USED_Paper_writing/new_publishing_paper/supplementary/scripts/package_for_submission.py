#!/usr/bin/env python3
"""package_for_submission.py -- copies the 13 Online Resources into ../for_submission/ for download and upload:
xlsx/ (9 spreadsheets), pdf/ (4 PDFs), ESM_all_Online_Resources.zip (all 13) and CAPTIONS.md (file -> caption, taken
from the "Supplementary Information" section of the manuscript, to paste into the submission system).

TAG (journal_TAG/TAG_submission_guidelines_2026-09-15.pdf, Supplementary Information): one file per Online Resource,
named ESM_1, ESM_2, ... in citation order, each with a concise caption; several files "may be collected in a .zip".
So the files stay separate (no merged PDF: Online Resources 4, 9, 12 and 13 are cited as separate files).
The unnumbered supplement (../unreferenced/) is not included: it is not cited in the text.
Run by build_all.sh after the builders (the copies are refreshed on every build). Created 2026-10-01.
"""
import re, shutil, zipfile, pathlib
from esm_common import SUPP, WORKING_FILE, AUTHORS

OUT = SUPP / "for_submission"
if OUT.exists():
    shutil.rmtree(OUT)                         # only ever holds copies made by this script
(OUT / "xlsx").mkdir(parents=True); (OUT / "pdf").mkdir()
files = []
for n in range(1, 14):
    f = [p for p in SUPP.glob(f"ESM_{n}.*") if p.suffix in (".xlsx", ".pdf")]
    assert len(f) == 1, (n, f)
    shutil.copy2(f[0], OUT / f[0].suffix[1:] / f[0].name)
    files.append(f[0])
with zipfile.ZipFile(OUT / "ESM_all_Online_Resources.zip", "w", zipfile.ZIP_DEFLATED) as z:
    for f in files:
        z.write(f, f.name)
t = WORKING_FILE.read_text(encoding="utf-8")
caps = dict((int(n), c.strip()) for n, c in re.findall(r"\*\*Online Resource (\d+)\*\* ([^\n]+)", t[t.index("# Supplementary Information"):]))
assert sorted(caps) == list(range(1, 14)), sorted(caps)
plain = lambda s: re.sub(r"\*+", "", s)
lines = ["# Online Resources (ESM) — files and captions for the TAG submission system", "",
         f"Generated by `scripts/package_for_submission.py`. Upload the 13 files separately (or the zip), each with its caption.",
         "Captions = the \"Supplementary Information\" section of the manuscript.", ""]
if "[" in AUTHORS:
    lines += ["**Before uploading:** the title block in every file still has placeholders (author names, corresponding author's "
              "affiliation and e-mail): set them in `scripts/esm_common.py` and run `scripts/build_all.sh` (checklist item 1).", ""]
lines += ["| file | caption |", "|---|---|"] + [f"| `{f.name}` | Online Resource {n}. {plain(caps[n])} |" for n, f in enumerate(files, 1)]
(OUT / "CAPTIONS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"packaged {len(files)} files -> {OUT} (xlsx/: {len(list((OUT/'xlsx').iterdir()))}, pdf/: {len(list((OUT/'pdf').iterdir()))}, "
      f"zip {round((OUT/'ESM_all_Online_Resources.zip').stat().st_size/1e6, 1)} MB, CAPTIONS.md)")
